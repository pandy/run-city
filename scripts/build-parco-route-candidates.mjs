import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const apiKey = process.env.PARCO_ANON_KEY;
if (!apiKey) {
  throw new Error('Set PARCO_ANON_KEY to Parco\'s public anonymous API key.');
}

const root = process.cwd();
const headers = { apikey: apiKey, Authorization: `Bearer ${apiKey}` };
const apiBase = 'https://api.parco.run/rest/v1';

async function fetchJson(url, init) {
  const response = await fetch(url, { ...init, headers: { ...headers, ...init?.headers } });
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}: ${url}`);
  return response.json();
}

const cities = await fetchJson(`${apiBase}/rpc/get_cities_with_stats`, {
  method: 'POST',
  headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify({ include_invisible: false }),
});

const placeFields = [
  'id', 'city_id', 'pathname', 'local_name', 'type', 'location',
  'longest_track_length', 'tracks_count', 'visits_count', 'is_closed',
].join(',');
const places = [];
for (let offset = 0; ; offset += 1000) {
  const page = await fetchJson(
    `${apiBase}/place?select=${placeFields}&is_visible=eq.true&limit=1000&offset=${offset}`,
  );
  places.push(...page);
  if (page.length < 1000) break;
}

const coreCitiesSource = await readFile(path.join(root, 'src/data/coreCities.ts'), 'utf8');
const coreIds = new Set(
  [...coreCitiesSource.matchAll(/\{ id: '([^']+)', name: '([^']+)'/g)].map((match) => match[1]),
);
const librarySource = await readFile(path.join(root, 'src/data/fullRouteLibrary.generated.ts'), 'utf8');
const existingNames = Object.fromEntries([...coreIds].map((id) => [id, []]));
for (const match of librarySource.matchAll(/"cityId": "([^"]+)"[\s\S]{0,250}?"name": "([^"]+)"/g)) {
  existingNames[match[1]]?.push(match[2]);
}

function normalizeName(value = '') {
  return value
    .trim()
    .replace(/[\s·—（）()\-]/g, '')
    .replace(/(跑步|健身|生态|城市|滨水|环湖|环岛|外圈|内圈|标准|塑胶|步道|绿道|跑道|公园|广场|体育中心|风光带|长廊|线路|路线|环线|线)$/g, '');
}

function namesOverlap(left, right) {
  const a = normalizeName(left);
  const b = normalizeName(right);
  return a.length >= 2 && b.length >= 2 && (a.includes(b) || b.includes(a));
}

const candidates = [];
for (const city of cities) {
  if (city.country_code !== 'CHN' || !coreIds.has(city.pathname)) continue;
  const existing = existingNames[city.pathname] ?? [];
  const pool = places
    .filter((place) => place.city_id === city.id)
    .filter((place) => !place.is_closed && place.tracks_count > 0 && place.local_name)
    .filter((place) => place.location?.coordinates?.length === 2)
    .filter((place) => (place.longest_track_length ?? 0) >= 400)
    .filter((place) => !existing.some((name) => namesOverlap(name, place.local_name)))
    .sort((a, b) => {
      const score = (place) => (place.visits_count ?? 0) * 20
        + (place.tracks_count ?? 0) * 5
        + (place.longest_track_length ?? 0) / 1000;
      return score(b) - score(a);
    });

  const selected = [];
  for (const place of pool) {
    if (selected.some((item) => namesOverlap(item.local_name, place.local_name))) continue;
    selected.push(place);
    if (selected.length === 3) break;
  }

  selected.forEach((place, index) => {
    candidates.push({
      id: `${city.pathname}-parco-${place.id}`,
      cityId: city.pathname,
      rank: 11 + index,
      name: place.local_name.trim(),
      distanceKm: Math.round(place.longest_track_length / 100) / 10,
      location: {
        latitude: place.location.coordinates[1],
        longitude: place.location.coordinates[0],
      },
      evidenceUrl: `https://parco.run/${city.pathname}/${place.pathname}`,
    });
  });
}

const output = `// Generated by scripts/build-parco-route-candidates.mjs.\n`
  + `// Only factual discovery fields are retained; community descriptions, photos and polylines are excluded.\n`
  + `export const parcoRouteCandidates = ${JSON.stringify(candidates, null, 2)} as const;\n`;

await writeFile(path.join(root, 'src/data/parcoRouteCandidates.generated.ts'), output);
console.log(`Generated ${candidates.length} Parco discovery candidates across ${new Set(candidates.map((item) => item.cityId)).size} cities.`);
