import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const apiKey = process.env.PARCO_ANON_KEY;
if (!apiKey) throw new Error('Set PARCO_ANON_KEY to Parco\'s public anonymous API key.');

const root = process.cwd();
const headers = { apikey: apiKey, Authorization: `Bearer ${apiKey}` };
const source = await readFile(path.join(root, 'src/data/parcoRouteCandidates.generated.ts'), 'utf8');
const match = source.match(/export const parcoRouteCandidates = ([\s\S]+) as const;\s*$/);
if (!match) throw new Error('Cannot parse parcoRouteCandidates.generated.ts');
const candidates = JSON.parse(match[1]);
const placeIds = candidates.map((candidate) => Number(candidate.id.match(/-parco-(\d+)$/)?.[1])).filter(Number.isInteger);

async function fetchJson(url) {
  const response = await fetch(url, { headers });
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}: ${url}`);
  return response.json();
}

const tracks = [];
for (let offset = 0; offset < placeIds.length; offset += 80) {
  const ids = placeIds.slice(offset, offset + 80).join(',');
  const query = new URLSearchParams({
    select: 'id,place_id,local_name,geometry,length',
    'place_id': `in.(${ids})`,
    order: 'id.asc',
  });
  tracks.push(...await fetchJson(`https://api.parco.run/rest/v1/place_track?${query.toString()}`));
}

function distanceKm(points) {
  const radians = (value) => value * Math.PI / 180;
  let total = 0;
  for (let index = 1; index < points.length; index += 1) {
    const [lon1, lat1] = points[index - 1];
    const [lon2, lat2] = points[index];
    const dLat = radians(lat2 - lat1);
    const dLon = radians(lon2 - lon1);
    const a = Math.sin(dLat / 2) ** 2
      + Math.cos(radians(lat1)) * Math.cos(radians(lat2)) * Math.sin(dLon / 2) ** 2;
    total += 6371 * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  }
  return total;
}

const bestTrackByPlace = new Map();
for (const track of tracks) {
  const coordinates = track.geometry?.type === 'LineString' ? track.geometry.coordinates : [];
  if (coordinates.length < 2) continue;
  const current = bestTrackByPlace.get(track.place_id);
  if (!current || Number(track.length ?? 0) > Number(current.length ?? 0)) {
    bestTrackByPlace.set(track.place_id, track);
  }
}

const geometries = {};
for (const candidate of candidates) {
  const placeId = Number(candidate.id.match(/-parco-(\d+)$/)?.[1]);
  const track = bestTrackByPlace.get(placeId);
  if (!track) continue;
  const coordinates = track.geometry.coordinates
    .filter((point) => Array.isArray(point) && point.length >= 2)
    .map(([longitude, latitude]) => ({ latitude, longitude }));
  if (coordinates.length < 2) continue;
  const calculatedDistanceKm = distanceKm(track.geometry.coordinates);
  const declaredDistanceKm = Number(track.length ?? 0) / 1000;
  const distance = declaredDistanceKm > 0 ? declaredDistanceKm : calculatedDistanceKm;
  if (!Number.isFinite(distance) || distance <= 0 || distance > 100) continue;
  geometries[candidate.id] = {
    distanceKm: Math.round(distance * 100) / 100,
    coordinates,
  };
}

const output = `// Generated by scripts/build-parco-route-geometries.mjs.\n`
  + `// Geometry is retained with source links in the candidate dataset for attribution.\n`
  + `export const parcoRouteGeometries: Record<string, { distanceKm: number; coordinates: Array<{ latitude: number; longitude: number }> }> = ${JSON.stringify(geometries, null, 2)};\n`;
await writeFile(path.join(root, 'src/data/parcoRouteGeometries.generated.ts'), output);
console.log(`Generated ${Object.keys(geometries).length}/${candidates.length} Parco route geometries from ${tracks.length} tracks.`);
